BEGIN;

CREATE TABLE IF NOT EXISTS public.template_blacklist (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phrase varchar(300) NOT NULL,
    category varchar(50),
    note text,
    created_at timestamp without time zone NOT NULL DEFAULT now(),
    updated_at timestamp without time zone NOT NULL DEFAULT now(),
    is_deleted boolean NOT NULL DEFAULT false
);

ALTER TABLE public.template_blacklist
    ADD COLUMN IF NOT EXISTS phrase varchar(300),
    ADD COLUMN IF NOT EXISTS category varchar(50),
    ADD COLUMN IF NOT EXISTS note text,
    ADD COLUMN IF NOT EXISTS created_at timestamp without time zone DEFAULT now(),
    ADD COLUMN IF NOT EXISTS updated_at timestamp without time zone DEFAULT now(),
    ADD COLUMN IF NOT EXISTS is_deleted boolean DEFAULT false;

UPDATE public.template_blacklist
SET created_at = COALESCE(created_at, now()),
    updated_at = COALESCE(updated_at, now()),
    is_deleted = COALESCE(is_deleted, false);

ALTER TABLE public.template_blacklist
    ALTER COLUMN phrase SET NOT NULL,
    ALTER COLUMN created_at SET NOT NULL,
    ALTER COLUMN updated_at SET NOT NULL,
    ALTER COLUMN is_deleted SET NOT NULL,
    ALTER COLUMN created_at SET DEFAULT now(),
    ALTER COLUMN updated_at SET DEFAULT now(),
    ALTER COLUMN is_deleted SET DEFAULT false;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'template_blacklist_phrase_not_blank'
    ) THEN
        ALTER TABLE public.template_blacklist
            ADD CONSTRAINT template_blacklist_phrase_not_blank
            CHECK (length(btrim(phrase)) > 0);
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS ix_template_blacklist_phrase_normalized
    ON public.template_blacklist ((lower(regexp_replace(btrim(phrase), '\s+', ' ', 'g'))))
    WHERE is_deleted = false;

COMMIT;
